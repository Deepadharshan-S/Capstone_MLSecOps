import { lazy, Suspense, useState } from 'react'
import {
  PageHeader, Tabs, LoadingState, Badge, Button,
} from '../components/ui/index.jsx'
import { Shield, Bell, Database, SlidersHorizontal, Target, RefreshCw } from '../components/icons.jsx'

// Tab panels are code-split like routes — the alerts feed is the landing
// tab, the heavier rule editor / hunt forms only load when opened.
const AlertsTab = lazy(() => import('./security/AlertsTab.jsx'))
const EventsTab = lazy(() => import('./security/EventsTab.jsx'))
const RulesTab = lazy(() => import('./security/RulesTab.jsx'))
const HuntsTab = lazy(() => import('./security/HuntsTab.jsx'))

const TABS = [
  { id: 'alerts', label: 'Alerts', icon: Bell },
  { id: 'events', label: 'Security events', icon: Database },
  { id: 'rules', label: 'Detection rules', icon: SlidersHorizontal },
  { id: 'hunts', label: 'Threat hunts', icon: Target },
]

export default function Security() {
  const [tab, setTab] = useState('alerts')
  // Each tab owns its own fetch, so the header can't call refetch directly.
  // Bumping a token instead lands in the active tab's fetch deps, which
  // re-arms it. Every tab guards its skeleton with `loading && !data`, so a
  // refresh repaints the rows in place rather than flashing a loader.
  const [refreshToken, setRefreshToken] = useState(0)

  return (
    <div className="page">
      <PageHeader
        icon={Shield}
        title="Security Center"
        subtitle="Alerts generated by the detection engine from security events — auto-refreshes as new alerts fire"
        badge={<Badge tone="accent" dot>live</Badge>}
        actions={
          <Button
            variant="secondary"
            icon={RefreshCw}
            onClick={() => setRefreshToken((t) => t + 1)}
          >
            Refresh
          </Button>
        }
      />

      <Tabs active={tab} onChange={setTab} tabs={TABS} />

      <Suspense fallback={<LoadingState label="Loading panel…" lg />}>
        {tab === 'alerts' && <AlertsTab refreshToken={refreshToken} />}
        {tab === 'events' && <EventsTab refreshToken={refreshToken} />}
        {tab === 'rules' && <RulesTab refreshToken={refreshToken} />}
        {tab === 'hunts' && <HuntsTab refreshToken={refreshToken} />}
      </Suspense>
    </div>
  )
}
