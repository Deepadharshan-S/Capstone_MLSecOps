import logging
import urllib.parse
from typing import Any, Optional
from sqlalchemy.orm import Session
from sqlalchemy import select

from app.core.config import settings
from app.models.dataset import Dataset
from app.schemas.threat_hunting import SecurityEventCreate
from app.services.threat_hunting.event_service import event_service
from app.services.threat_hunting.alert_service import alert_service
from app.services.threat_hunting.detection_engine import detection_engine

logger = logging.getLogger("threat_hunting.storage_detector")

# Classification Constants
CLASSIFICATION_AUTHORIZED = "authorized_lakefs_operation"
CLASSIFICATION_SUSPICIOUS = "suspicious_storage_mutation"
CLASSIFICATION_UNVERIFIED = "unverified_storage_activity"
CLASSIFICATION_IGNORED = "ignored_unmonitored_bucket"


class StorageMutationDetector:
    """
    Evaluates MinIO S3 bucket notifications for out-of-band storage mutations
    and direct lakeFS bypass tampering attempts (MITRE ATT&CK T1565.001, T1530).
    """

    def is_bucket_monitored(self, bucket_name: str) -> bool:
        """
        Verifies if the bucket belongs to monitored storage namespaces.
        """
        monitored = getattr(settings, "MINIO_MONITORED_BUCKETS", ["lakefs"])
        return bucket_name in monitored

    def get_dataset_by_key(self, db: Session, bucket_name: str, object_key: str) -> Optional[Dataset]:
        """
        Attempts to correlate an S3 object key with registered datasets in the DB.
        Dataset storage namespaces are formatted as 's3://<bucket>/<repo_name>'.
        """
        try:
            # First path component in lakeFS blockstore is typically the repository name
            clean_key = object_key.lstrip("/")
            parts = clean_key.split("/", 1)
            repo_candidate = parts[0] if parts else ""

            # Check if any dataset storage_namespace contains bucket and repo_candidate
            datasets = db.execute(select(Dataset)).scalars().all()
            for ds in datasets:
                ns = ds.storage_namespace or ""
                # Normalize ns: e.g. s3://lakefs/my_repo -> bucket 'lakefs', repo 'my_repo'
                if ns.startswith("s3://"):
                    ns_path = ns[5:].strip("/")
                    ns_parts = ns_path.split("/", 1)
                    if len(ns_parts) >= 2:
                        b_name, r_name = ns_parts[0], ns_parts[1]
                        if b_name == bucket_name and (r_name == repo_candidate or clean_key.startswith(f"{r_name}/")):
                            return ds
                    elif len(ns_parts) == 1 and ns_parts[0] == bucket_name:
                        return ds
                if ds.name == repo_candidate:
                    return ds
        except Exception as e:
            logger.debug(f"Failed to correlate object '{bucket_name}/{object_key}' with dataset: {e}")
        return None

    def classify_mutation(
        self,
        db: Session,
        bucket_name: str,
        raw_key: str,
        event_name: str,
        principal_id: Optional[str],
        source_ip: Optional[str] = None,
        size_bytes: Optional[int] = None,
        etag: Optional[str] = None,
        version_id: Optional[str] = None,
        sequencer: Optional[str] = None,
    ) -> dict[str, Any]:
        """
        Executes evidence-based classification of MinIO storage mutations:
        1. Authorized: expected lakeFS service user performing normal immutable blockstore operations.
        2. Suspicious: unauthorized identities modifying dataset storage or direct metadata tampering.
        3. Unverified: inconclusive identity or activity on monitored buckets requiring audit telemetry.
        """
        # S3 object keys in notifications are URL-encoded
        object_key = urllib.parse.unquote_plus(raw_key)

        if not self.is_bucket_monitored(bucket_name):
            return {
                "classification": CLASSIFICATION_IGNORED,
                "severity": "LOW",
                "should_alert": False,
                "reason": f"Bucket '{bucket_name}' is not in monitored buckets list.",
                "object_key": object_key,
                "bucket": bucket_name,
            }

        # Test events generated by MinIO configuration probing
        if "testevent" in event_name.lower():
            return {
                "classification": CLASSIFICATION_AUTHORIZED,
                "severity": "LOW",
                "should_alert": False,
                "reason": f"MinIO test event '{event_name}' received successfully.",
                "object_key": object_key,
                "bucket": bucket_name,
            }

    def correlate_lakefs_evidence(
        self,
        db: Session,
        bucket_name: str,
        object_key: str,
        dataset: Optional[Dataset] = None,
        is_remove_event: bool = False,
    ) -> tuple[bool, str]:
        """
        Evaluates lakeFS commit, branch, and metadata catalog evidence for the given S3 object key.
        Returns (is_verified, reason).
        """
        try:
            # 1. LakeFS internal action execution manifests and internal operational files
            if any(p in object_key for p in ("_lakefs_actions/", "_lakefs/actions", "lakefs.metadata")):
                return True, "lakeFS internal action or system metadata file"

            # 2. Check if repository is known in DB or lakeFS
            repo_candidate = object_key.split("/", 1)[0]
            if not dataset:
                dataset = self.get_dataset_by_key(db, bucket_name, object_key)

            repo_name = dataset.name if dataset else repo_candidate

            is_known_repo = (dataset is not None)
            if not is_known_repo:
                from app.services.dataset.lakefs_service import lakefs_service
                try:
                    is_known_repo = lakefs_service.repository_exists(repo_name)
                except Exception:
                    is_known_repo = False

            if not is_known_repo:
                return False, f"Repository '{repo_name}' is not recognized in SentinelML or lakeFS catalog"

            # 3. Legitimate GC deletion of non-metadata object in recognized repository
            if is_remove_event and not any(p in object_key for p in ("_lakefs/", "_lakefs_actions/")):
                return True, "Verified lakeFS garbage collection deletion of unreferenced blockstore object"

            # 4. In lakeFS, physical blockstore objects are placed under data/ or hashed prefixes, or _lakefs/
            parts = object_key.split("/")
            if len(parts) >= 2 and (parts[1] == "data" or "_lakefs/" in object_key):
                return True, "Verified lakeFS physical blockstore object under data/ or _lakefs/ prefix"

            # Otherwise, lacks confirmed commit or staging reference
            return False, "No active lakeFS commit, action manifest, or physical blockstore reference found"
        except Exception as e:
            logger.debug(f"Error correlating lakeFS evidence for '{bucket_name}/{object_key}': {e}")
            return False, f"Correlation error: {str(e)}"

    def classify_mutation(
        self,
        db: Session,
        bucket_name: str,
        raw_key: str,
        event_name: str,
        principal_id: Optional[str],
        source_ip: Optional[str] = None,
        size_bytes: Optional[int] = None,
        etag: Optional[str] = None,
        version_id: Optional[str] = None,
        sequencer: Optional[str] = None,
    ) -> dict[str, Any]:
        """
        Executes evidence-based classification of MinIO storage mutations:
        1. Authorized: verified lakeFS operation with confirmed catalog / commit / blockstore correlation.
        2. Suspicious: unauthorized identities modifying dataset storage, direct tabular bypass writes, or metadata tampering.
        3. Unverified: inconclusive correlation evidence on monitored buckets retained as unverified telemetry.
        """
        # S3 object keys in notifications are URL-encoded
        object_key = urllib.parse.unquote_plus(raw_key)

        if not self.is_bucket_monitored(bucket_name):
            return {
                "classification": CLASSIFICATION_IGNORED,
                "severity": "LOW",
                "should_alert": False,
                "reason": f"Bucket '{bucket_name}' is not in monitored buckets list.",
                "object_key": object_key,
                "bucket": bucket_name,
            }

        # Test events generated by MinIO configuration probing
        if "testevent" in event_name.lower():
            return {
                "classification": CLASSIFICATION_AUTHORIZED,
                "severity": "LOW",
                "should_alert": False,
                "reason": f"MinIO test event '{event_name}' received successfully.",
                "object_key": object_key,
                "bucket": bucket_name,
            }

        clean_actor = (principal_id or "anonymous").strip()
        expected_principals = getattr(
            settings, "expected_lakefs_principals", [getattr(settings, "MINIO_ROOT_USER", "minioadmin")]
        )
        is_lakefs_identity = (clean_actor in expected_principals)

        dataset = self.get_dataset_by_key(db, bucket_name, object_key)
        is_dataset_namespace = dataset is not None
        is_metadata_path = any(
            part in object_key for part in ("_lakefs/", "_lakefs_actions/", "lakefs.metadata")
        )
        is_remove_event = "objectremoved" in event_name.lower()
        is_create_event = "objectcreated" in event_name.lower()
        has_tabular_extension = any(
            object_key.lower().endswith(ext)
            for ext in (".csv", ".parquet", ".pq", ".tsv", ".json", ".tab", ".data")
        )

        # Check 1: Direct mutation by an unauthorized, non-lakeFS identity into dataset storage or metadata
        if not is_lakefs_identity and (is_dataset_namespace or is_metadata_path):
            return {
                "classification": CLASSIFICATION_SUSPICIOUS,
                "severity": "HIGH",
                "should_alert": True,
                "dataset_name": dataset.name if dataset else None,
                "reason": (
                    f"Direct {event_name} by unauthorized principal '{clean_actor}' "
                    f"targeting protected storage path '{bucket_name}/{object_key}' bypassing lakeFS version controls."
                ),
                "object_key": object_key,
                "bucket": bucket_name,
            }

        # Check 2: Unauthorized identity modifying any object in monitored bucket
        if not is_lakefs_identity:
            return {
                "classification": CLASSIFICATION_SUSPICIOUS,
                "severity": "HIGH",
                "should_alert": True,
                "dataset_name": dataset.name if dataset else None,
                "reason": (
                    f"Unauthorized identity '{clean_actor}' executed {event_name} "
                    f"on monitored bucket '{bucket_name}/{object_key}' without lakeFS credentials."
                ),
                "object_key": object_key,
                "bucket": bucket_name,
            }

        # Check 3: Identity is lakeFS service identity, but event is an unexpected metadata deletion
        if is_lakefs_identity and is_remove_event and is_metadata_path:
            return {
                "classification": CLASSIFICATION_SUSPICIOUS,
                "severity": "HIGH",
                "should_alert": True,
                "dataset_name": dataset.name if dataset else None,
                "reason": (
                    f"Unexpected deletion of lakeFS metadata '{bucket_name}/{object_key}' "
                    f"detected in underlying MinIO storage."
                ),
                "object_key": object_key,
                "bucket": bucket_name,
            }

        # Check 4: Identity is lakeFS service identity, but write is directly a logical dataset file
        # (LakeFS blockstore NEVER writes raw dataset files directly; it writes opaque hashed objects under data/)
        if is_lakefs_identity and is_create_event and has_tabular_extension and not is_metadata_path and not ("/data/" in object_key or object_key.startswith("data/")):
            return {
                "classification": CLASSIFICATION_SUSPICIOUS,
                "severity": "HIGH",
                "should_alert": True,
                "dataset_name": dataset.name if dataset else None,
                "reason": (
                    f"Direct write of logical tabular file '{bucket_name}/{object_key}' "
                    f"using service credentials bypassed lakeFS blockstore abstraction."
                ),
                "object_key": object_key,
                "bucket": bucket_name,
            }

        # Check 5: LakeFS service identity with correlation evidence evaluation
        if is_lakefs_identity:
            is_verified, corr_reason = self.correlate_lakefs_evidence(
                db, bucket_name, object_key, dataset, is_remove_event=is_remove_event
            )
            if is_verified:
                return {
                    "classification": CLASSIFICATION_AUTHORIZED,
                    "severity": "LOW",
                    "should_alert": False,
                    "dataset_name": dataset.name if dataset else None,
                    "reason": (
                        f"Authorized lakeFS storage operation ({event_name}) "
                        f"performed by service user '{clean_actor}' on '{bucket_name}/{object_key}' ({corr_reason})."
                    ),
                    "object_key": object_key,
                    "bucket": bucket_name,
                }
            else:
                return {
                    "classification": CLASSIFICATION_UNVERIFIED,
                    "severity": "LOW",
                    "should_alert": False,
                    "dataset_name": dataset.name if dataset else None,
                    "reason": (
                        f"Storage mutation ({event_name}) by service user '{clean_actor}' "
                        f"on '{bucket_name}/{object_key}' lacked confirmed lakeFS correlation ({corr_reason}). Retained as unverified."
                    ),
                    "object_key": object_key,
                    "bucket": bucket_name,
                }

        # Fallback: Inconclusive / Unverified activity
        return {
            "classification": CLASSIFICATION_UNVERIFIED,
            "severity": "LOW",
            "should_alert": False,
            "dataset_name": dataset.name if dataset else None,
            "reason": (
                f"Unverified storage activity ({event_name}) on '{bucket_name}/{object_key}' "
                f"by actor '{clean_actor}'. Retained as unverified."
            ),
            "object_key": object_key,
            "bucket": bucket_name,
        }

    def process_minio_record(
        self,
        db: Session,
        record: dict[str, Any],
    ) -> Optional[dict[str, Any]]:
        """
        Parses a single MinIO event record, evaluates classification,
        and ingests a SecurityEvent if relevant.
        """
        s3_info = record.get("s3") or {}
        bucket_info = s3_info.get("bucket") or {}
        object_info = s3_info.get("object") or {}

        bucket_name = bucket_info.get("name")
        raw_key = object_info.get("key")
        event_name = record.get("eventName", "s3:ObjectCreated:Put")
        event_time = record.get("eventTime")

        user_ident = record.get("userIdentity") or {}
        req_params = record.get("requestParameters") or {}
        principal_id = user_ident.get("principalId") or req_params.get("principalId") or "unknown"
        source_ip = req_params.get("sourceIPAddress")

        size_bytes = object_info.get("size")
        etag = object_info.get("eTag")
        version_id = object_info.get("versionId")
        sequencer = object_info.get("sequencer")

        if not bucket_name or not raw_key:
            logger.warning("MinIO notification record missing bucket.name or object.key.")
            return None

        classification_res = self.classify_mutation(
            db=db,
            bucket_name=bucket_name,
            raw_key=raw_key,
            event_name=event_name,
            principal_id=principal_id,
            source_ip=source_ip,
            size_bytes=size_bytes,
            etag=etag,
            version_id=version_id,
            sequencer=sequencer,
        )

        # Ignore unmonitored buckets completely
        if classification_res["classification"] == CLASSIFICATION_IGNORED:
            return classification_res

        clean_key = classification_res["object_key"]
        resource_id = f"{bucket_name}/{clean_key}"
        correlation_id = sequencer or f"{bucket_name}/{clean_key}/{event_time or ''}/{event_name}"

        # Ingest SecurityEvent for suspicious mutations or unverified activity
        # Suspicious mutations receive HIGH severity; unverified receive LOW severity.
        severity = classification_res["severity"]
        should_alert = classification_res["should_alert"]

        event_attributes = {
            "bucket": bucket_name,
            "object_key": clean_key,
            "event_name": event_name,
            "event_time": event_time,
            "principal_id": principal_id,
            "source_ip": source_ip,
            "size_bytes": size_bytes,
            "etag": etag,
            "version_id": version_id,
            "sequencer": sequencer,
            "classification": classification_res["classification"],
            "reason": classification_res["reason"],
            "dataset_name": classification_res.get("dataset_name"),
        }

        # Ingest SecurityEvent through existing idempotent event service
        try:
            sec_event = event_service.ingest_event(
                db=db,
                event_in=SecurityEventCreate(
                    event_type="storage.unversioned_mutation",
                    source="minio_notification",
                    actor_id=principal_id,
                    resource_type="s3_object",
                    resource_id=resource_id,
                    severity=severity,
                    attributes=event_attributes,
                    correlation_id=correlation_id,
                ),
            )

            # If this is a suspicious mutation requiring an alert, correlate immediately
            if should_alert and sec_event:
                try:
                    detections = detection_engine.evaluate_all_rules(db)
                    for d in detections:
                        if d.resource_id == resource_id or any(ev_id == sec_event.id for ev_id in d.event_ids):
                            alert_service.process_detection(db, d)
                except Exception as alert_err:
                    logger.error(f"Error triggering immediate alert for storage mutation: {alert_err}")

            classification_res["security_event_id"] = str(sec_event.id) if sec_event else None
        except Exception as e:
            logger.error(f"Failed to persist SecurityEvent for MinIO storage mutation: {e}", exc_info=True)
            raise

        return classification_res


storage_mutation_detector = StorageMutationDetector()
