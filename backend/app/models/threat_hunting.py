class Alert(BaseModel):
    """
    Stores security alerts generated by the detection engine or threat hunting jobs.
    """
    __tablename__ = "alerts"

    title: Mapped[str] = mapped_column(
        String(200),
        nullable=False,
        index=True,
    )

    description: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    severity: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="MEDIUM",
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default="OPEN",
        index=True,
    )

    detection_source: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        default="rule_engine",
        index=True,
    )

    rule_id: Mapped[Optional[UUID]] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("detection_rules.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    rule_version: Mapped[Optional[int]] = mapped_column(
        Integer,
        nullable=True,
    )

    mitre_attack_id: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    mitre_atlas_id: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    first_seen: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    last_seen: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    event_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=1,
    )

    supporting_evidence: Mapped[dict] = mapped_column(
        JSON_TYPE,
        nullable=False,
        default=dict,
    )

    dedup_key: Mapped[Optional[str]] = mapped_column(
        String(128),
        nullable=True,
        index=True,
    )

    assignee_id: Mapped[Optional[UUID]] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    resolution_reason: Mapped[Optional[str]] = mapped_column(
        String(500),
        nullable=True,
    )

    resolved_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Relationships
    rule: Mapped[Optional["DetectionRule"]] = relationship(
        "DetectionRule",
        back_populates="alerts",
    )

    event_links: Mapped[list["AlertEvent"]] = relationship(
        "AlertEvent",
        back_populates="alert",
        cascade="all, delete-orphan",
    )

    history: Mapped[list["AlertHistory"]] = relationship(
        "AlertHistory",
        back_populates="alert",
        cascade="all, delete-orphan",
        order_by="AlertHistory.created_at.desc()",
    )


class AlertEvent(BaseModel):
    """
    Associates an alert with triggering security events.
    """
    __tablename__ = "alert_events"

    alert_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("alerts.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    event_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("security_events.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    associated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Relationships
    alert: Mapped["Alert"] = relationship("Alert", back_populates="event_links")
    event: Mapped["SecurityEvent"] = relationship("SecurityEvent", back_populates="alert_links")


class AlertHistory(BaseModel):
    """
    Tracks state transitions, investigations, and notes for an alert.
    """
    __tablename__ = "alert_histories"

    alert_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("alerts.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    actor_id: Mapped[Optional[str]] = mapped_column(
        String(100),
        nullable=True,
    )

    previous_status: Mapped[Optional[str]] = mapped_column(
        String(30),
        nullable=True,
    )

    new_status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
    )

    notes: Mapped[Optional[str]] = mapped_column(
        String(1000),
        nullable=True,
    )

    # Relationships
    alert: Mapped["Alert"] = relationship("Alert", back_populates="history")


